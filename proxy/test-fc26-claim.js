const REPO = 'amiller/fc26-nfts';

if (typeof paper_id !== 'string' || !paper_id.match(/^[a-zA-Z0-9._-]+$/))
  throw new Error('Invalid paper_id');
if (typeof email_hash !== 'string' || !email_hash.match(/^[a-f0-9]{64}$/))
  throw new Error('Invalid email_hash: expected sha256 hex');
if (typeof recipient !== 'string' || !recipient.match(/^0x[a-fA-F0-9]{40}$/))
  throw new Error('Invalid recipient: expected ETH address');

const emailKey = `rate:email:${email_hash}`;
const lastEmail = store.get(emailKey);
if (lastEmail && Date.now() - Number(lastEmail) < 600000)
  throw new Error('Rate limited: 1 claim per email per 10 minutes');

const globalKey = 'rate:global';
const globalLog = JSON.parse(store.get(globalKey) || '[]');
const recent = globalLog.filter(t => Date.now() - t < 600000);
if (recent.length >= 5)
  throw new Error('Rate limited: max 5 claims per 10 minutes');

const body = `paper_id: ${paper_id}
email_hash: ${email_hash}
recipient: ${recipient}

---
> **How this works:** Filing this issue triggers a GitHub Action that sends a verification email to the address matching this hash. Reply with the code from that email to complete your claim and mint the NFT.
>
> \`email_hash\` = sha256(CLAIM_SALT + your_email), where CLAIM_SALT = "FC26-rump-session-2026". Your email is not revealed in this issue.
>
> **Trust model:** There's nothing special about this repo. The ZK proof is generated by a pinned prover image (\`sha256:d85e563...\`) running in GitHub Actions with [Sigstore](https://www.sigstore.dev/) attestation. Anyone with the same commit and an SES key can run this workflow and independently verify proofs. See the [README](https://github.com/amiller/fc26-nfts#how-it-works) for details.`;

const res = await fetch(`https://api.github.com/repos/${REPO}/issues`, {
  method: 'POST',
  headers: {
    'Authorization': `token ${secrets.GITHUB_TOKEN}`,
    'Accept': 'application/vnd.github.v3+json',
    'User-Agent': 'oauth3-enclave'
  },
  body: JSON.stringify({
    title: `[PAPER] Claim paper #${paper_id}`,
    body: body,
    labels: ['paper-pending']
  })
});

if (!res.ok) {
  const err = await res.text();
  throw new Error(`GitHub API error ${res.status}: ${err}`);
}

const issue = await res.json();

store.set(emailKey, String(Date.now()));
recent.push(Date.now());
store.set(globalKey, JSON.stringify(recent));

return { issue_number: issue.number, url: issue.html_url };
